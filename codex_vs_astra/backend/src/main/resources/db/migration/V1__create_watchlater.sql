CREATE TABLE WLC_USERS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(100 CHAR) NOT NULL
);
CREATE TABLE WLC_POSTS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR2(200 CHAR) NOT NULL,
    VIDEO_URL VARCHAR2(1000 CHAR) NOT NULL,
    CONTENT CLOB,
    STATUS VARCHAR2(10 CHAR) DEFAULT 'NEW' NOT NULL,
    AUTHOR VARCHAR2(50 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT WLC_POST_STATUS_CK CHECK (STATUS IN ('NEW', 'DONE'))
);
CREATE INDEX WLC_POST_CREATED_IDX ON WLC_POSTS (CREATED_AT DESC, ID DESC);
